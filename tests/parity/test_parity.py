# tests/parity/test_parity.py
"""Event parity against the frozen legacy fixtures (design §9.2).

Fixtures are generated by ``generate_fixtures.py`` (run manually, never by
pytest): it replays each reference .traj through BOTH the legacy brain and
ToolPulse on the same step stream.  These tests consume the frozen artifacts
only — no legacy environment is required.  Events are the contract here; hint
text parity is template-level and covered by tests/hints/test_template.py.

The replay ToolPulse is constructed with EXACTLY the generator's configuration
(explicit parser/labeler/offline detector/ListSink).  ``for_swe_repo()`` would
default to an ONLINE detector whose suppression state can mask events the
generator captured on the same stream (reviewer Minor 1: config skew).
"""
import json
from pathlib import Path

import pytest

from toolpulse.core.types import StepObservation
from toolpulse.detectors.multi_granularity import MultiGranularityDetector
from toolpulse.hints.sinks import ListSink
from toolpulse.middleware import ToolPulse
from toolpulse.parsing.sweagent import SweAgentParser
from toolpulse.semantics.repo.labeler import RepoLabeler

FIXTURES = sorted(
    fixture for fixture in (Path(__file__).parent / "fixtures").glob("*.json")
    # legacy-replay schema only; the eventful_synthetic golden has its own
    # schema ({"steps": [{raw_action,...}], "events": [...]}) and its own test.
    if "legacy_events" in json.loads(fixture.read_text(encoding="utf-8"))["steps"][0]
)


def _rows(fixture: Path):
    return json.loads(fixture.read_text(encoding="utf-8"))["steps"]


def _replay_pulse() -> tuple[ToolPulse, ListSink]:
    # Keep in sync with toolpulse_run() in generate_fixtures.py.
    sink = ListSink()
    pulse = ToolPulse(parser=SweAgentParser(), labeler=RepoLabeler("python"),
                      detector=MultiGranularityDetector(offline=True), hint_sink=sink)
    return pulse, sink


@pytest.mark.parametrize("fixture", FIXTURES, ids=lambda path: path.stem)
def test_unmodified_steps_match_legacy_exactly(fixture):
    rows = _rows(fixture)
    pulse, sink = _replay_pulse()
    for i, row in enumerate(rows):
        n = len(sink.hints)
        pulse.observe_step(StepObservation(
            raw_action=row["action"], observation=row["observation"], thought=row["thought"],
            execution_time=row["execution_time"], host_context=row.get("host_context")))
        fired = [h.event.to_dict() for h in sink.hints[n:]]
        if row["divergence"] is None:
            assert fired == row["legacy_events"], f"step {i}: parity broken"
        else:
            assert fired == row["toolpulse_events"], f"step {i}: new golden broken"


@pytest.mark.parametrize("fixture", FIXTURES, ids=lambda path: path.stem)
def test_state_transition_total_counter(fixture):
    rows = _rows(fixture)
    pulse, _ = _replay_pulse()
    for row in rows:
        pulse.observe_step(StepObservation(raw_action=row["action"], observation=row["observation"],
                                           thought=row["thought"], execution_time=row["execution_time"],
                                           host_context=row.get("host_context")))
    assert pulse.state.total_actions_seen == len(rows)
